from __future__ import annotations

import ast
import json
from dataclasses import dataclass
from typing import Any

from .schemas import Operation, TemplateManifest, VerificationCheck, VerificationReport


class CodeAssembler:
    def assemble(self, template: TemplateManifest, op: Operation, context: dict[str, Any] | None = None) -> str:
        params = {
            "op_id": op.op_id,
            "operation_type": op.type,
            "inputs": op.inputs,
            "expected": op.expected,
            "context": context or {},
        }
        # repr() is intentionally used rather than string interpolation with raw
        # JSON so generated Unreal Python receives Python-native dict/list types.
        script = template.script.replace("{{ params_json }}", repr(params))
        header = (
            "# Auto-generated by CineU research system.\n"
            "# Source of truth: operation IR + template manifest.\n"
            "# Do not edit this file manually unless you are debugging a failed run.\n\n"
        )
        return header + script.rstrip() + "\n"


_SIMPLE_TYPES: dict[str, type | tuple[type, ...]] = {
    "str": str,
    "int": int,
    "float": (int, float),
    "bool": bool,
    "list": list,
    "dict": dict,
}


@dataclass
class StaticVerifier:
    forbidden_import_roots: tuple[str, ...] = (
        "os",
        "sys",
        "subprocess",
        "socket",
        "requests",
        "pathlib",
        "shutil",
        "multiprocessing",
        "http",
        "urllib",
        "ftplib",
    )
    allowed_import_roots: tuple[str, ...] = (
        "unreal",
        "cineu_world_ops",
        "cineu_asset_ops",
        "cineu_sequence_ops",
        "cineu_camera_ops",
        "cineu_render_ops",
        "cineu_anim_ops",
        "cineu_verify_ops",
    )
    forbidden_calls: tuple[str, ...] = (
        "eval",
        "exec",
        "open",
        "compile",
        "__import__",
        "input",
        "globals",
        "locals",
        "vars",
        "getattr",
        "setattr",
        "delattr",
    )

    def verify(self, script: str, op: Operation, template: TemplateManifest | None = None) -> VerificationReport:
        checks: list[VerificationCheck] = []
        diagnostics: dict[str, Any] = {}
        try:
            tree = ast.parse(script)
            checks.append(VerificationCheck(name="python_syntax", passed=True))
        except SyntaxError as exc:
            checks.append(VerificationCheck(name="python_syntax", passed=False, message=str(exc)))
            return VerificationReport(op_id=op.op_id, stage="static", passed=False, checks=checks, diagnostics={"error_type": "PYTHON_SYNTAX_ERROR"})

        imports_ok, bad_imports, imported_roots = self._check_imports(tree)
        calls_ok, bad_calls = self._check_calls(tree)
        checks.append(VerificationCheck(name="import_allowlist", passed=imports_ok, actual=bad_imports))
        checks.append(VerificationCheck(name="forbidden_calls", passed=calls_ok, actual=bad_calls))

        if template is not None:
            checks.extend(self._check_template_inputs(template, op))
            checks.append(VerificationCheck(name="template_operation_type", passed=template.operation_type == op.type, expected=template.operation_type, actual=op.type))
            template_allowed = set(template.safety.get("allowed_imports", [])) | {"cineu_verify_ops"}
            wrapper_imports = {root for root in imported_roots if root.startswith("cineu_")}
            extra = sorted(wrapper_imports - template_allowed)
            checks.append(VerificationCheck(name="template_import_scope", passed=not extra, expected=sorted(template_allowed), actual=extra))

        passed = all(c.passed for c in checks)
        if not passed:
            failed_names = [c.name for c in checks if not c.passed]
            ast_failed = bool(bad_imports or bad_calls or "import_allowlist" in failed_names or "forbidden_calls" in failed_names)
            template_failed = any(name.startswith("template_") for name in failed_names)
            if ast_failed and not template_failed:
                diagnostics["error_type"] = "AST_GUARD_VIOLATION"
            elif template_failed and not ast_failed:
                diagnostics["error_type"] = "TEMPLATE_INPUT_VIOLATION"
            else:
                diagnostics["error_type"] = "AST_GUARD_OR_TEMPLATE_INPUT_VIOLATION"
            diagnostics["bad_imports"] = bad_imports
            diagnostics["bad_calls"] = bad_calls
            diagnostics["failed_checks"] = [c.model_dump(mode="json") for c in checks if not c.passed]
        return VerificationReport(op_id=op.op_id, stage="static", passed=passed, checks=checks, diagnostics=diagnostics)

    def _check_imports(self, tree: ast.AST) -> tuple[bool, list[str], set[str]]:
        imports_ok = True
        bad_imports: list[str] = []
        imported_roots: set[str] = set()
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                for alias in node.names:
                    root = alias.name.split(".")[0]
                    imported_roots.add(root)
                    if root in self.forbidden_import_roots or root not in self.allowed_import_roots:
                        imports_ok = False
                        bad_imports.append(alias.name)
            elif isinstance(node, ast.ImportFrom):
                mod = node.module or ""
                root = mod.split(".")[0]
                imported_roots.add(root)
                if root in self.forbidden_import_roots or root not in self.allowed_import_roots:
                    imports_ok = False
                    bad_imports.append(mod)
        return imports_ok, bad_imports, imported_roots

    def _check_calls(self, tree: ast.AST) -> tuple[bool, list[str]]:
        calls_ok = True
        bad_calls: list[str] = []
        for node in ast.walk(tree):
            if isinstance(node, ast.Call):
                name = ""
                if isinstance(node.func, ast.Name):
                    name = node.func.id
                elif isinstance(node.func, ast.Attribute):
                    name = node.func.attr
                if name in self.forbidden_calls:
                    calls_ok = False
                    bad_calls.append(name)
        return calls_ok, bad_calls

    def _check_template_inputs(self, template: TemplateManifest, op: Operation) -> list[VerificationCheck]:
        checks: list[VerificationCheck] = []
        for key, expected_type_name in template.inputs_schema.items():
            exists = key in op.inputs
            checks.append(VerificationCheck(name=f"template_input_exists:{key}", passed=exists, expected=expected_type_name, actual=None if not exists else "present"))
            if not exists:
                continue
            expected_type = _SIMPLE_TYPES.get(str(expected_type_name))
            if expected_type is None:
                # Unknown rich type annotations are advisory in this research version.
                checks.append(VerificationCheck(name=f"template_input_type:{key}", passed=True, expected=expected_type_name, actual=type(op.inputs[key]).__name__, message="Advisory type only."))
            else:
                checks.append(
                    VerificationCheck(
                        name=f"template_input_type:{key}",
                        passed=isinstance(op.inputs[key], expected_type),
                        expected=expected_type_name,
                        actual=type(op.inputs[key]).__name__,
                    )
                )
        return checks
